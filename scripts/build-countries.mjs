// Generates src/data/countries.js: current country outlines (Natural Earth 1:110m), simplified.
// They serve as a base for the 19th- and 20th-century maps, when borders already look like today's.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url)));
const fc = feature(topo, topo.objects.countries), out = {};
const r1 = x => Math.round(x * 10) / 10;
for (const f of fc.features) {
  const name = f.properties.name; if (!name || !f.geometry) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates, rings = [];
  for (const p of polys) {
    const r = p[0];                                                     // outer ring only
    if (Math.max(...r.map(q => q[0])) - Math.min(...r.map(q => q[0])) > 180) continue;   // crosses ±180°
    const pts = [];
    for (const [x, y] of r) { const q = [r1(x), r1(y)], l = pts[pts.length - 1]; if (!l || Math.hypot(q[0] - l[0], q[1] - l[1]) >= 0.25) pts.push(q); }
    if (pts.length >= 4) rings.push(pts);
  }
  if (rings.length) out[name] = rings;
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n');
writeFileSync(new URL('../src/data/countries.js', import.meta.url),
  `// Generated by scripts/build-countries.mjs from Natural Earth (1:110m). Do not edit by hand.\n// Current outlines: [outer ring of each part], in [lon, lat].\nexport const COUNTRIES = {\n${body}\n};\n`);
console.log(Object.keys(out).length, 'countries');
